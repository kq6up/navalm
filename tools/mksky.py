#!/usr/bin/env python3
# Rebuild the bundled display-only constellation catalogue; requires Python 3.
from pathlib import Path
import math,re,json,hashlib
root=Path(__file__).resolve().parent.parent
def sex(s):
 sign=-1 if s.startswith('-') else 1
 v=[float(x) for x in s.lstrip('+-').split(':')]
 return sign*sum(x/60**i for i,x in enumerate(v))
def row(line):
 f=line.split(',');ra=f[2].split('|');dec=f[3].split('|')
 return [f[0].split('|')[0],sex(ra[0])*15,sex(dec[0]),float(ra[1] or 0) if len(ra)>1 else 0,float(dec[1] or 0) if len(dec)>1 else 0,float(f[4])]
def vec(ra,dec):
 a,d=math.radians(ra),math.radians(dec)
 return (math.cos(a)*math.cos(d),math.sin(a)*math.cos(d),math.sin(d))
nav=[row(l) for l in (root/'navstars.edb').read_text().splitlines() if l and not l.startswith('#')]
cat=[]
for l in (root/'data/sky/SKY2k65.edb').read_text(encoding='latin1').splitlines():
 if l and not l.startswith('#'):
  try: cat.append(row(l))
  except (ValueError,IndexError): pass
vectors=[vec(s[1],s[2]) for s in cat]
assert len(nav)==58, "Update combined display indices when changing the navigation catalogue"
navv=[vec(s[1],s[2]) for s in nav]
points=[]; used={};figs=[];current=None;previous=None;edges=[];worst=0
for line in (root/'data/sky/classicfigs.csf').read_text().splitlines():
 l=line.strip()
 if not l or l.startswith('#'):continue
 if not re.match(r'^[012]\s',l):
  current={'name':l,'edges':[]};figs.append(current);previous=None;continue
 code,ra,dec,*_=l.split();v=vec(sex(ra)*15,sex(dec))
 nearest=max(range(len(cat)),key=lambda i:sum(a*b for a,b in zip(v,vectors[i])))
 dist=math.degrees(math.acos(min(1,sum(a*b for a,b in zip(v,vectors[nearest])))))
 worst=max(worst,dist)
 if dist>.18:
  assert current['name']=='Cygnus' and 'draw chi' in l, 'Unexpected unmatched figure vertex: '+l
  print('Approximate chi Cygni vertex from figure file:',l)
  cat.append(['chi Cygni (figure)' ,sex(ra)*15,sex(dec),0,0,6.5]);vectors.append(v);nearest=len(cat)-1
 ni=max(range(len(nav)),key=lambda i:sum(a*b for a,b in zip(vectors[nearest],navv[i])))
 if sum(a*b for a,b in zip(vectors[nearest],navv[ni]))>math.cos(math.radians(.005)): idx=ni
 else:
  if nearest not in used: used[nearest]=len(points);points.append(cat[nearest])
  idx=65+used[nearest]
 if int(code) and previous!=idx:current['edges'].append((previous,idx));edges.append((previous,idx))
 previous=idx
print('catalogue',len(cat),'nav',len(nav),'extra',len(points),'figures',len(figs),'edges',len(edges),'max match deg',worst)
out=['/* Generated by tools/mksky.py; XEphem classicfigs.csf and SKY2k65.edb.',' * MIT: Copyright (c) 1990-2020 Elwood Charles Downey. See libastro/LICENSE.XEphem. */','static const NavStarCat sky_context_catalogue[] = {']
for s in points:out.append('    {'+json.dumps(s[0])+', '+', '.join(f'{x:.10f}' for x in s[1:])+'},')
out+=['};','static const struct { int a,b,figure; } sky_figure_edges[] = {']
for fi,f in enumerate(figs):
 for a,b in f['edges']:out.append(f'    {{{a},{b},{fi}}},')
out+=['};','static const char *sky_figure_names[] = {']+[f'    {json.dumps(f["name"])},' for f in figs]+['};','']
(root/'navsky_data.inc').write_text('\n'.join(out))
