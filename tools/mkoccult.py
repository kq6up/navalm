#!/usr/bin/env python3
"""Compile the complete bundled XEphem magnitude-6.5 catalogue for occultations."""
from pathlib import Path
import json, math
root = Path(__file__).resolve().parent.parent
def sex(s):
    sign = -1 if s.startswith('-') else 1
    return sign * sum(float(x)/60**i for i,x in enumerate(s.lstrip('+-').split(':')))
rows=[]; rejected=[]
for line in (root/'data/sky/SKY2k65.edb').read_text(encoding='latin1').splitlines():
    if not line or line.startswith('#'): continue
    f=line.split(',')
    if len(f)<6 or f[5]!='2000' or not f[2].split('|')[0] or not f[3].split('|')[0]:
        rejected.append(line); continue
    ra=f[2].split('|'); dec=f[3].split('|')
    vals=[sex(ra[0])*15,sex(dec[0]),float(ra[1]) if len(ra)>1 and ra[1] else 0,
          float(dec[1]) if len(dec)>1 and dec[1] else 0,float(f[4])]
    assert all(math.isfinite(v) for v in vals)
    rows.append('    {{'+json.dumps(f[0].split('|')[0])+', '+', '.join(f'{v:.10f}' for v in vals)+'}, '+json.dumps(f[0])+', '+str(int('D' in f[1].split('|')))+'},')
assert len(rows)>8000
(root/'navoccult_data.inc').write_text('/* Generated by tools/mkoccult.py from data/sky/SKY2k65.edb.\n * XEphem MIT license: libastro/LICENSE.XEphem; see data/sky/README.md. */\nstatic const OccStar catalog[] = {\n'+'\n'.join(rows)+'\n};\n')
print(f'Compiled {len(rows)} stars with aliases and double-star flags.')

for line in rejected: print('Excluded malformed upstream row:', line)
